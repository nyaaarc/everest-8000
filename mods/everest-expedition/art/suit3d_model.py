# ---------------------------------------------------------------------------
# UV packing
# ---------------------------------------------------------------------------
def iter_boxes(part):
    yield from part.boxes
    for c in part.children:
        yield from iter_boxes(c)


def uv_footprint(tex):
    w, h, d = tex
    import math
    return int(math.ceil(2 * (d + w))), int(math.ceil(d + h))


def uv_regions(texture):
    """uv key -> tex dims, for every layer drawn from `texture` (shared keys must agree)."""
    regions = {}
    for layer in LAYERS:
        if layer.texture != texture:
            continue
        for part in layer.parts.values():
            for b in iter_boxes(part):
                if b.uv in regions and regions[b.uv] != b.tex:
                    raise ValueError(f"uv {b.uv!r} used with sizes {regions[b.uv]} and {b.tex}")
                regions[b.uv] = b.tex
    return regions


def pack(texture):
    """Shelf-pack every uv region of a texture; returns {uv key: (u, v)}."""
    tw, th, _ = TEXTURES[texture]
    regions = uv_regions(texture)
    order = sorted(regions, key=lambda k: (-uv_footprint(regions[k])[1], -uv_footprint(regions[k])[0], k))
    shelves = []  # [y, height, x_cursor]
    placed = {}
    for key in order:
        fw, fh = uv_footprint(regions[key])
        for shelf in shelves:
            if fh <= shelf[1] and shelf[2] + fw <= tw:
                placed[key] = (shelf[2], shelf[0])
                shelf[2] += fw
                break
        else:
            y = shelves[-1][0] + shelves[-1][1] if shelves else 0
            if y + fh > th or fw > tw:
                raise ValueError(f"{texture}: no room for {key} ({fw}x{fh}) at y={y}")
            shelves.append([y, fh, fw])
            placed[key] = (0, y)
    return placed


UV = {name: pack(name) for name in TEXTURES}


def uv_of(texture, key):
    return UV[texture][key]


