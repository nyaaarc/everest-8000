@dataclass
class Box:
    name: str
    x: tuple
    y: tuple
    z: tuple
    uv: str = None
    tex: tuple = None
    mirror: bool = False

    def __post_init__(self):
        if self.uv is None:
            self.uv = self.name
        if self.tex is None:
            self.tex = tuple(max(1, int(round(b - a))) for a, b in (self.x, self.y, self.z))

    @property
    def grow(self):
        return tuple(((b - a) - t) / 2 for (a, b), t in zip((self.x, self.y, self.z), self.tex))

    @property
    def origin(self):
        g = self.grow
        return (self.x[0] + g[0], self.y[0] + g[1], self.z[0] + g[2])

    def mirrored(self):
        return Box(self.name, (-self.x[1], -self.x[0]), self.y, self.z, self.uv, self.tex, not self.mirror)


@dataclass
class Part:
    name: str
    pose: tuple = (0, 0, 0, 0, 0, 0)  # x, y, z, xRot, yRot, zRot (radians)
    boxes: list = field(default_factory=list)
    children: list = field(default_factory=list)

    def mirrored(self, name=None):
        x, y, z, xr, yr, zr = self.pose
        return Part(name or self.name, (-x, y, z, xr, -yr, -zr),
                    [b.mirrored() for b in self.boxes], [c.mirrored() for c in self.children])


@dataclass
class Layer:
    name: str
    texture: str
    parts: dict  # root part name -> Part
    doc: str = ""


ROOT_POSES = {
    "head": (0, 0, 0), "hat": (0, 0, 0), "body": (0, 0, 0),
    "right_arm": (-5, 2, 0), "left_arm": (5, 2, 0),
    "right_leg": (-1.9, 12, 0), "left_leg": (1.9, 12, 0),
}
ROOT_ORDER = ["head", "hat", "body", "right_arm", "left_arm", "right_leg", "left_leg"]


def humanoid(name, texture, doc="", **parts):
    """A HumanoidModel-compatible layer; right limbs given, left limbs mirrored."""
    roots = {}
    for root in ROOT_ORDER:
        if root in parts:
            p = parts[root]
        elif root.startswith("left_") and ("right_" + root[5:]) in parts:
            p = parts["right_" + root[5:]].mirrored(root)
        else:
            p = Part(root)
        p.name = root
        x, y, z = ROOT_POSES[root]
        p.pose = (x, y, z, 0, 0, 0)
        roots[root] = p
    return Layer(name, texture, roots, doc)


