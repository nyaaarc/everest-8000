def jf(v):
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    if s in ("-0", ""):
        s = "0"
    return s + "F"


def java_part(lines, layer, part, parent_var, indent, var_counter):
    var = f"{part.name.replace('-', '_')}{var_counter[0]}" if part.name not in ROOT_ORDER else part.name.replace("right_", "right").replace("left_", "left")
    var_counter[0] += 1
    x, y, z, xr, yr, zr = part.pose
    if any((xr, yr, zr)):
        pose = f"PartPose.offsetAndRotation({jf(x)}, {jf(y)}, {jf(z)}, {jf(xr)}, {jf(yr)}, {jf(zr)})"
    elif any((x, y, z)):
        pose = f"PartPose.offset({jf(x)}, {jf(y)}, {jf(z)})"
    else:
        pose = "PartPose.ZERO"
    pad = " " * indent
    if part.boxes:
        cubes = ["CubeListBuilder.create()"]
        mirror = False
        for b in part.boxes:
            if b.mirror != mirror:
                cubes.append(".mirror()" if b.mirror else ".mirror(false)")
                mirror = b.mirror
            u, v = uv_of(layer.texture, b.uv)
            ox, oy, oz = b.origin
            w, h, d = b.tex
            gx, gy, gz = b.grow
            grow = "CubeDeformation.NONE" if not any((gx, gy, gz)) else (
                f"new CubeDeformation({jf(gx)})" if gx == gy == gz else f"new CubeDeformation({jf(gx)}, {jf(gy)}, {jf(gz)})")
            cubes.append(f'.addBox("{b.name}", {jf(ox)}, {jf(oy)}, {jf(oz)}, {w}, {h}, {d}, {grow}, {u}, {v})')
        builder = ("\n" + pad + "        ").join(cubes)
    else:
        builder = "CubeListBuilder.create()"
    needs_var = bool(part.children)
    lhs = f"PartDefinition {var} = " if needs_var else ""
    lines.append(f'{pad}{lhs}{parent_var}.addOrReplaceChild("{part.name}", {builder},\n{pad}        {pose});')
    for c in part.children:
        java_part(lines, layer, c, var, indent, var_counter)


def camel(s):
    parts = s.split("_")
    return parts[0] + "".join(p.title() for p in parts[1:])


