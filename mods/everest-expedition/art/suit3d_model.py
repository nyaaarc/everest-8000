"""3D down suit: geometry spec, UV packing and Java codegen.

This file is the single source of truth for the suit's boxes. It feeds:
  - suit3d_textures.py   paints every box face into the packed UV layout
  - preview_suit3d.py    renders the model off-line and checks for z-fighting
  - DownSuitModels.java  generated here (python suit3d_model.py --java <out dir>)

Units are model pixels (1/16 block) in ModelPart space: +Y is down, -Z is the
front (face), -X is the wearer's right. Every box is given by its extents; its
texel size defaults to the rounded extents and any difference becomes a
CubeDeformation, so faces keep (close to) one texel per pixel.

Boxes that share a `uv` key share texels (all torso baffles look the same).
Left limbs are generated by mirroring the right ones, like vanilla (mirror()).
"""
